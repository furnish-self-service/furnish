//! Linux launchers and Wayland taskbars identify the app by its desktop file ID, even when
//! the window has its own icon. Override the package entry in the user's XDG data directory.
use std::{fs, io::ErrorKind, path::{Path, PathBuf}};

use anyhow::{Context, Result};
use glib::{KeyFile, KeyFileFlags};

const ENTRY: &str = "applications/furnish.desktop";
const GROUP: &str = "Desktop Entry";
const MARKER: &str = "# Generated by furnish for organization branding: ";

fn digest(bytes: &[u8]) -> glib::GString {
    glib::compute_checksum_for_data(glib::ChecksumType::Sha256, bytes).expect("GLib supports SHA-256")
}

pub fn refresh(home: &Path, system: &[PathBuf], name: &str, rgba: Option<&[u8]>) -> Result<()> {
    let entry = home.join(ENTRY);
    let previous = match fs::symlink_metadata(&entry) {
        Ok(metadata) if metadata.file_type().is_file() => {
            let Ok(contents) = String::from_utf8(fs::read(&entry)?) else { return Ok(()) };
            let Some((header, body)) = contents.split_once('\n') else { return Ok(()) };
            if header.strip_prefix(MARKER) != Some(digest(body.as_bytes()).as_str()) {
                return Ok(()); // A launcher the person made or edited.
            }
            Some(contents)
        }
        Ok(_) => return Ok(()),
        Err(err) if err.kind() == ErrorKind::NotFound => None,
        Err(err) => return Err(err.into()),
    };
    let flags = KeyFileFlags::KEEP_COMMENTS | KeyFileFlags::KEEP_TRANSLATIONS;
    let icons = home.join("furnish/launcher-icons");
    let old_icon = previous.as_ref().and_then(|text| {
        let old = KeyFile::new();
        old.load_from_data(text, flags).ok()?;
        let icon = PathBuf::from(old.string(GROUP, "Icon").ok()?.as_str());
        let hash = icon.file_name()?.to_str()?.strip_suffix(".png")?;
        (hash.len() == 64 && hash.bytes().all(|b| b.is_ascii_hexdigit()) && icon.parent() == Some(icons.as_path())).then_some(icon)
    });
    let package = system.iter().filter(|dir| dir.as_path() != home).map(|dir| dir.join(ENTRY)).find(|file| file.is_file());
    let mut icon = None;
    if let Some(package) = package.filter(|_| name != "furnish" || rgba.is_some()) {
        let keys = KeyFile::new();
        keys.load_from_file(package, flags)?;
        // Keep the installed command, link handlers, actions and package-specific settings.
        // Localized keys would take precedence over the organization's name and logo.
        for key in keys.keys(GROUP)?.iter() {
            if (name != "furnish" && key.starts_with("Name[")) || (rgba.is_some() && key.starts_with("Icon[")) {
                keys.remove_key(GROUP, key)?;
            }
        }
        if name != "furnish" {
            keys.set_string(GROUP, "Name", &name.replace(char::is_control, " "));
        }
        if let Some(rgba) = rgba {
            let hash = digest(rgba);
            let path = icons.join(format!("{hash}.png"));
            fs::create_dir_all(&icons)?;
            if !path.is_file() {
                glib::file_set_contents(&path, &crate::app_icon::png(rgba)?)?;
            }
            keys.set_string(GROUP, "Icon", path.to_str().context("launcher icon path is not UTF-8")?);
            icon = Some(path);
        }
        let body = keys.to_data();
        let contents = format!("{MARKER}{}\n{body}", digest(body.as_bytes()));
        if previous.as_ref() != Some(&contents) {
            fs::create_dir_all(entry.parent().unwrap())?;
            glib::file_set_contents(&entry, contents.as_bytes())?;
        }
    } else if previous.is_some() {
        fs::remove_file(&entry)?;
    }
    if let Some(old) = old_icon.filter(|p| Some(p) != icon.as_ref()) {
        match fs::remove_file(old) {
            Err(err) if err.kind() != ErrorKind::NotFound => return Err(err.into()),
            _ => {}
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use gio::prelude::AppInfoExt;

    const PACKAGE: &str = "[Desktop Entry]\nType=Application\nName=furnish\nName[de]=Pakete\nIcon=package-icon\nIcon[de]=paket-symbol\nExec=/usr/bin/env furnish-gui %u\nMimeType=x-scheme-handler/furnish;\nActions=Tray;\nStartupWMClass=furnish\nX-Package-Version=one\n\n[Desktop Action Tray]\nName=Start in tray\nName[de]=Im Infobereich starten\nExec=/usr/bin/env furnish-gui --hidden\n";

    fn package(dir: &Path, contents: &str) -> PathBuf {
        fs::create_dir_all(dir.join("applications")).unwrap();
        let path = dir.join(ENTRY);
        fs::write(&path, contents).unwrap();
        path
    }

    fn keys(path: &Path) -> KeyFile {
        let keys = KeyFile::new();
        keys.load_from_file(path, KeyFileFlags::KEEP_TRANSLATIONS).unwrap();
        keys
    }

    #[test]
    fn overrides_the_preferred_package_and_preserves_actions_and_localizations() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path().join("user data");
        let preferred = tmp.path().join("preferred");
        let fallback = tmp.path().join("system");
        let installed = package(&preferred, PACKAGE);
        package(&fallback, &PACKAGE.replace("X-Package-Version=one", "X-Package-Version=two"));
        let system = [preferred, fallback];
        let entry = home.join(ENTRY);
        let name = "Tools ü\\Office\nExec=unchanged";
        refresh(&home, &system, name, None).unwrap();
        let branded = keys(&entry);
        assert_eq!(branded.string(GROUP, "Name").unwrap(), "Tools ü\\Office Exec=unchanged");
        assert!(branded.string(GROUP, "Name[de]").is_err());
        assert_eq!(branded.string(GROUP, "Icon[de]").unwrap(), "paket-symbol");
        assert_eq!(branded.string(GROUP, "X-Package-Version").unwrap(), "one");
        assert_eq!(branded.string(GROUP, "Exec").unwrap(), "/usr/bin/env furnish-gui %u");
        assert_eq!(branded.string("Desktop Action Tray", "Name[de]").unwrap(), "Im Infobereich starten");
        let desktop = gio::DesktopAppInfo::from_filename(&entry).unwrap();
        assert_eq!(desktop.name(), "Tools ü\\Office Exec=unchanged");
        assert!(desktop.supports_uris());
        assert_eq!(desktop.list_actions().as_slice(), &["Tray"]);

        fs::write(installed, PACKAGE.replace("X-Package-Version=one", "X-Package-Version=updated")).unwrap();
        refresh(&home, &system, name, None).unwrap();
        assert_eq!(keys(&entry).string(GROUP, "X-Package-Version").unwrap(), "updated");

        refresh(&home, &system, "furnish", None).unwrap();
        assert!(!entry.exists());
        assert_eq!(keys(&system[0].join(ENTRY)).string(GROUP, "Name[de]").unwrap(), "Pakete");
    }

    #[test]
    fn changing_the_logo_replaces_only_the_managed_icon() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path().join("home");
        let system = [tmp.path().join("system")];
        package(&system[0], PACKAGE);
        let entry = home.join(ENTRY);
        let rgba = vec![0xab; 256 * 256 * 4];
        refresh(&home, &system, "furnish", Some(&rgba)).unwrap();
        let branded = keys(&entry);
        assert_eq!(branded.string(GROUP, "Name[de]").unwrap(), "Pakete");
        assert!(branded.string(GROUP, "Icon[de]").is_err());
        let icon = PathBuf::from(branded.string(GROUP, "Icon").unwrap().as_str());
        assert!(fs::read(&icon).unwrap().starts_with(b"\x89PNG\r\n\x1a\n"));
        let other = icon.with_file_name("my-own.png");
        fs::write(&other, "personal icon").unwrap();

        let mut updated = rgba;
        updated[0] = 0x12;
        refresh(&home, &system, "furnish", Some(&updated)).unwrap();
        let current = PathBuf::from(keys(&entry).string(GROUP, "Icon").unwrap().as_str());
        assert_ne!(icon, current);
        assert!(!icon.exists());
        assert!(current.is_file());

        refresh(&home, &system, "furnish", None).unwrap();
        assert!(!entry.exists() && !current.exists());
        assert_eq!(fs::read_to_string(other).unwrap(), "personal icon");
    }

    #[test]
    fn private_and_edited_launchers_survive_policy_refresh_and_reset() {
        let tmp = tempfile::tempdir().unwrap();
        let home = tmp.path().join("home");
        let system = [tmp.path().join("system")];
        package(&system[0], PACKAGE);
        let entry = package(&home, PACKAGE);
        for name in ["Organization", "furnish"] {
            refresh(&home, &system, name, None).unwrap();
            assert_eq!(fs::read_to_string(&entry).unwrap(), PACKAGE);
        }

        fs::remove_file(&entry).unwrap();
        refresh(&home, &system, "Organization", None).unwrap();
        let edited = fs::read_to_string(&entry).unwrap().replace("Name=Organization", "Name=Personal launcher");
        fs::write(&entry, &edited).unwrap();
        for name in ["Updated organization", "furnish"] {
            refresh(&home, &system, name, None).unwrap();
            assert_eq!(fs::read_to_string(&entry).unwrap(), edited);
        }

        fs::remove_file(&entry).unwrap();
        std::os::unix::fs::symlink(system[0].join(ENTRY), &entry).unwrap();
        refresh(&home, &system, "Organization", None).unwrap();
        assert!(entry.is_symlink());
        assert_eq!(fs::read_to_string(&entry).unwrap(), PACKAGE);
    }
}
